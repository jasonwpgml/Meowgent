import AppKit
import Carbon

/// 자리 비움(AFK), 화면 잠금·잠자기, 보안 입력 공백, 클립보드, 분당 활동량, 상태 점검.
final class SystemWatcher {
    private let store: Store
    private let tap: InputTap
    private var timers: [Timer] = []
    private var afk = false
    private var secureOn = false
    private var lastPasteboard = NSPasteboard.general.changeCount
    var health: [String: Any] = [:]

    init(store: Store, tap: InputTap) {
        self.store = store
        self.tap = tap
    }

    func start() {
        timers.append(Timer.scheduledTimer(withTimeInterval: 5, repeats: true) { [weak self] _ in
            self?.checkIdle(); self?.checkSecureInput()
        })
        timers.append(Timer.scheduledTimer(withTimeInterval: 60, repeats: true) { [weak self] _ in
            self?.flushActivity(); self?.writeHealth()
        })
        if Privacy.config.captureClipboard {
            timers.append(Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in
                self?.checkClipboard()
            })
        }
        let dnc = DistributedNotificationCenter.default()
        dnc.addObserver(forName: .init("com.apple.screenIsLocked"), object: nil, queue: .main) { [weak self] _ in
            self?.system("lock")
        }
        dnc.addObserver(forName: .init("com.apple.screenIsUnlocked"), object: nil, queue: .main) { [weak self] _ in
            self?.system("unlock")
        }
        let wnc = NSWorkspace.shared.notificationCenter
        wnc.addObserver(forName: NSWorkspace.willSleepNotification, object: nil, queue: .main) { [weak self] _ in
            self?.flushActivity(); self?.system("sleep")
        }
        wnc.addObserver(forName: NSWorkspace.didWakeNotification, object: nil, queue: .main) { [weak self] _ in
            self?.system("wake")
        }
        writeHealth()
    }

    private func system(_ what: String) {
        store.write(Event("afk", payload: ["event": what, "status": (what == "lock" || what == "sleep") ? "afk" : "active"]))
        if what == "lock" || what == "sleep" { afk = true }
    }

    private func checkIdle() {
        let anyInput = CGEventType(rawValue: ~0)!
        let idle = CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: anyInput)
        if !afk && idle >= Privacy.config.afkSeconds {
            afk = true
            var e = Event("afk", payload: ["event": "idle", "status": "afk", "idle_s": Int(idle)])
            e.ts = Date().timeIntervalSince1970 - idle   // 경계는 마지막 입력 시각으로 소급
            store.write(e)
        } else if afk && idle < 5 {
            afk = false
            store.write(Event("afk", payload: ["event": "input", "status": "active"]))
        }
    }

    /// 어떤 앱이 보안 입력을 켜면 시스템 전체 키 탭이 키를 못 받는다 → 공백을 명시한다.
    private func checkSecureInput() {
        let on = IsSecureEventInputEnabled()
        guard on != secureOn else { return }
        secureOn = on
        var e = Event("secure", payload: ["status": on ? "on" : "off"], privacy: "secure_gap")
        e.fillContext()
        store.write(e)
    }

    /// 비밀번호 관리자는 복사할 때 "숨김/일시" 표시를 붙인다 (nspasteboard.org 관례)
    private static func isConcealed(_ types: [String]) -> Bool {
        types.contains { $0 == "org.nspasteboard.ConcealedType" || $0 == "org.nspasteboard.TransientType"
            || $0 == "org.nspasteboard.AutoGeneratedType" || $0.hasPrefix("com.agilebits") }
    }

    private func checkClipboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastPasteboard else { return }
        lastPasteboard = pb.changeCount
        let types = pb.types?.map(\.rawValue) ?? []
        var e = Event("clipboard")
        e.fillContext()
        let concealed = SystemWatcher.isConcealed(types)
        if concealed || Context.shared.snapshot.blocked {
            e.privacy = "blocked"
            store.write(e)
            return
        }
        guard let s = pb.string(forType: .string), !s.isEmpty else {
            e.payload = ["kind": types.contains("public.png") || types.contains("public.tiff") ? "image" : "other"]
            store.write(e)
            return
        }
        let (redacted, masked) = Privacy.redact(String(s.prefix(Privacy.config.maxClipboardChars)))
        e.payload = ["kind": "text", "text": redacted, "chars": s.count]
        if masked { e.privacy = "masked" }
        store.write(e)
    }

    /// Cmd+V 순간: 무엇을(클립보드 내용) 어디에(앱·창·주소·입력창) 붙여넣었나. 붙여넣은 글자 수를 돌려준다.
    @discardableResult
    func recordPaste(field: (role: String, label: String?)?) -> (chars: Int, sensitive: Bool) {
        let pb = NSPasteboard.general
        let types = pb.types?.map(\.rawValue) ?? []
        var e = Event("paste")
        e.fillContext()
        var payload: [String: Any] = [:]
        if let field { payload["field_role"] = field.role; if let l = field.label { payload["field"] = l } }
        let concealed = SystemWatcher.isConcealed(types)
        if concealed || Context.shared.snapshot.blocked || field?.role == "secure" {
            e.privacy = "blocked"
            e.payload = payload
            store.write(e)
            return (0, false)
        }
        guard let s = pb.string(forType: .string), !s.isEmpty else {
            payload["kind"] = types.contains("public.png") || types.contains("public.tiff") ? "image"
                : (types.contains("public.file-url") ? "file" : "other")
            e.payload = payload
            store.write(e)
            return (0, false)
        }
        let (redacted, masked) = Privacy.redact(String(s.prefix(Privacy.config.maxClipboardChars)))
        payload["kind"] = "text"
        payload["text"] = redacted
        payload["chars"] = s.count
        if s.count > Privacy.config.maxClipboardChars { payload["truncated"] = true }
        e.payload = payload
        if masked { e.privacy = "masked" }
        store.write(e)
        return (s.count, masked)
    }

    private func flushActivity() {
        let a = tap.drain()
        guard a.keys + a.clicks + a.scrolls + a.mouse > 0 else { return }
        var e = Event("activity", payload: ["keys": a.keys, "clicks": a.clicks, "scrolls": a.scrolls,
                                           "mouse_px": a.mouse, "period_s": 60])
        e.fillContext()
        store.write(e)
    }

    func writeHealth() {
        health = [
            "ax_trusted": AXIsProcessTrusted(),
            "input_monitoring": CGPreflightListenEventAccess(),
            "tap_enabled": tap.isEnabled,
            "tap_reenabled": tap.reenabled,
            "secure_input": secureOn,
            "events_written": store.written,
            "db_bytes": store.sizeBytes,
        ]
        store.write(Event("health", payload: health), force: true)
    }
}
